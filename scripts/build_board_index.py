"""Generate databases/board_profiles.json from the PlatformIO Registry.

    python -m scripts.build_board_index

GET /v3/packages/platformio/platform/espressif32/boards returns every board of the
espressif32 platform with its MCU. ShipSafe uses this to map `board = ...` in
platformio.ini to a chip family, and to warn when the selected chip profile does not
match the project's board.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "databases" / "board_profiles.json"
URL = "https://api.registry.platformio.org/v3/packages/platformio/platform/espressif32/boards"

# Which ShipSafe hardware profile covers which MCU family. None = no verified profile yet.
MCU_TO_PROFILE = {"ESP32": "esp32_wroom_32", "ESP32S2": None, "ESP32S3": None, "ESP32C3": None, "ESP32C6": None}


def main() -> int:
    response = requests.get(URL, timeout=30, headers={"User-Agent": "ShipSafe-scanner/2.0"})
    response.raise_for_status()
    boards = {}
    for board in response.json():
        mcu = board.get("mcu")
        name = board.get("name") or ""
        boards[board["id"]] = {"name": name, "mcu": mcu, "vendor": board.get("vendor"),
                               "profile": MCU_TO_PROFILE.get(mcu),
                               "module_note": ("WROVER module: GPIO16/GPIO17 may be wired to PSRAM; the WROOM-32 "
                                               "profile does not model this." if "wrover" in (board["id"] + name).lower()
                                               else None)}
    OUTPUT.write_text(json.dumps({
        "_comment": "Generated by scripts/build_board_index.py from the PlatformIO Registry boards endpoint.",
        "source": URL,
        "retrieved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "mcu_to_profile": MCU_TO_PROFILE,
        "boards": dict(sorted(boards.items())),
    }, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {len(boards)} boards to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
